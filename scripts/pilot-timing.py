"""Writes src/pilot/timing.generated.ts from pilot-short/voice/words.json.

Subtitle cards: 2-4 words, built sentence by sentence; a one-word sentence joins the next one
when it ends with '...' or is 'Welcome!', otherwise it joins the previous card.
Red keywords (FISH, BARREL ROLL, DRIVE-THRU) are marked on the cards that contain them.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
words = json.loads((ROOT / "pilot-short/voice/words.json").read_text())
KEYS = [["FISH"], ["BARREL ROLL"], ["DRIVE-THRU"]]

def clean(w):
    return re.sub(r"[\"“”]", "", w["w"])

def sentence_groups(ws):
    groups, cur = [], []
    for i, w in enumerate(ws):
        cur.append(i)
        if re.search(r"[.!?]\"?$|\.\.\.$", clean(w)):
            groups.append(cur); cur = []
    if cur:
        groups.append(cur)
    return groups

groups = sentence_groups(words)
# merge rules for one-word sentences
merged = []
i = 0
while i < len(groups):
    g = groups[i]
    if len(g) == 1:
        t = clean(words[g[0]]).lower()
        if (t.endswith("...") or t == "welcome!") and i + 1 < len(groups):
            groups[i + 1] = g + groups[i + 1]
            i += 1
            continue
        if merged:
            merged[-1] = merged[-1] + g
            i += 1
            continue
    merged.append(g)
    i += 1
groups = merged

def chunk(n):
    if n <= 4:
        return [n]
    k = -(-n // 4)
    sizes, left = [], n
    for j in range(k):
        s = round(left / (k - j))
        sizes.append(s); left -= s
    return sizes

cards = []
for g in groups:
    pos = 0
    for size in chunk(len(g)):
        idx = g[pos:pos + size]; pos += size
        text = " ".join(clean(words[i]) for i in idx)
        s = words[idx[0]]["s"]; e = words[idx[-1]]["e"]
        keys = []
        for k in KEYS:
            phrase = " ".join(k)
            if phrase.upper().replace("-", "") and phrase.lower() in text.lower():
                keys.append(phrase)
        cards.append({"s": s, "e": e, "text": text.upper(), "n": size, "keys": keys})

# each red keyword is shown once: keep it only on its first card
seen = set()
for c in cards:
    c["keys"] = [k for k in c["keys"] if k not in seen]
    seen.update(c["keys"])
for a, b in zip(cards, cards[1:]):
    if a["e"] > b["s"]:
        a["e"] = b["s"]
bad = [c["text"] for c in cards if c["n"] < 2 or c["n"] > 4]
assert not bad, bad

lines = ["// Generated by scripts/pilot-timing.py from pilot-short/voice/words.json. Do not edit by hand.",
         "export type Card = {s: number; e: number; text: string; keys?: string[]};", "",
         "export const WORDS: {w: string; s: number; e: number}[] = ["]
for w in words:
    lines.append(f"  {{w: {json.dumps(clean(w))}, s: {w['s']}, e: {w['e']}}},")
lines += ["];", "", "export const CARDS: Card[] = ["]
for c in cards:
    keys = f", keys: {json.dumps(c['keys'])}" if c["keys"] else ""
    lines.append(f"  {{s: {round(c['s'], 3)}, e: {round(c['e'], 3)}, text: {json.dumps(c['text'])}{keys}}},")
lines += ["];", ""]
(ROOT / "src/pilot/timing.generated.ts").write_text("\n".join(lines))
print("cards:", len(cards), "keyed:", [c["text"] for c in cards if c["keys"]])
for c in cards:
    print(f"{c['s']:6.2f}-{c['e']:6.2f} {c['text']}")
