"""Writes src/janitor/timing.generated.ts from janitor-short/voice/words.json.

Subtitle cards: 2-4 words, cut at sentence ends when a card already has two words, and never inside a key
phrase. Red keywords (ORBIT, RECYCLED PEE, MY CAR) are marked on their first card only.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
words = json.loads((ROOT / "janitor-short/voice/words.json").read_text())
KEYS = [["ORBIT"], ["RECYCLED", "PEE"], ["MY", "CAR"]]
# Forced card breaks at these word start times (seconds): the cards "PARKING LOT." and "ON MY CAR."
FORCE_BREAK = (57.284, 57.967)  # the words 'parking' and 'On' in words.json (the voice is fitted to the speech); re-check after each fit


def clean(w):
    return re.sub(r"[\"“”]", "", w["w"])


def ends_sentence(t):
    return bool(re.search(r"[.!?]\"?$|\.\.\.$", t))


def key_start(i):
    """Return the key phrase that starts at word index i, if any."""
    for k in KEYS:
        seq = [clean(words[i + j]).lower().strip(".,!?...:;") for j in range(len(k)) if i + j < len(words)]
        if len(seq) == len(k) and all(seq[j] == k[j].lower() for j in range(len(k))):
            return k
    return None


groups, cur = [], []
for i, w in enumerate(words):
    k = key_start(i)
    forced = any(abs(w["s"] - t) < 0.01 for t in FORCE_BREAK)
    if (k or forced) and len(cur) >= 2:
        groups.append(cur); cur = []
    cur.append(i)
    if len(cur) == 4 or (ends_sentence(clean(w)) and len(cur) >= 2):
        groups.append(cur); cur = []
if cur:
    if groups and len(cur) == 1 and len(groups[-1]) >= 3:
        # a lone last word takes the previous card's last word, so both cards stay at 2-4 words
        cur.insert(0, groups[-1].pop())
    if groups and len(cur) == 1:
        groups[-1].append(cur[0])
    else:
        groups.append(cur)

cards = []
for g in groups:
    text = " ".join(clean(words[i]) for i in g)
    keys = []
    for k in KEYS:
        phrase = " ".join(k)
        if phrase.lower() in re.sub(r"[.,!?:;]", "", text).lower():
            keys.append(phrase)
    cards.append({"s": words[g[0]]["s"], "e": words[g[-1]]["e"], "text": text.upper(), "n": len(g), "keys": keys})

seen = set()
for c in cards:
    c["keys"] = [k for k in c["keys"] if k not in seen]
    seen.update(c["keys"])
for a, b in zip(cards, cards[1:]):
    if a["e"] > b["s"]:
        a["e"] = b["s"]

bad = [c["text"] for c in cards if c["n"] < 2 or c["n"] > 4]
assert not bad, bad
long_cards = [c["text"] for c in cards if len(c["text"]) > 24]

lines = ["// Generated by scripts/janitor-timing.py from janitor-short/voice/words.json. Do not edit by hand.",
         "export type Card = {s: number; e: number; text: string; keys?: string[]};", "",
         "export const WORDS: {w: string; s: number; e: number}[] = ["]
for w in words:
    lines.append(f"  {{w: {json.dumps(clean(w))}, s: {w['s']}, e: {w['e']}}},")
lines += ["];", "", "export const CARDS: Card[] = ["]
for c in cards:
    keys = f", keys: {json.dumps(c['keys'])}" if c["keys"] else ""
    lines.append(f"  {{s: {round(c['s'], 3)}, e: {round(c['e'], 3)}, text: {json.dumps(c['text'])}{keys}}},")
lines += ["];", ""]
out = ROOT / "src/janitor/timing.generated.ts"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print("cards:", len(cards), "keyed:", [c["text"] for c in cards if c["keys"]])
print("long (>24 chars, check the wrap):", long_cards)
for c in cards:
    print(f"{c['s']:6.2f}-{c['e']:6.2f} {c['text']}")
